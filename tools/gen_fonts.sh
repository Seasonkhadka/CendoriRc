#!/usr/bin/env bash
# Regenerate the custom Korean+Latin subset fonts used by src/ui.
#
# Requires: node/npx (uses lv_font_conv via npx) and Windows "Malgun Gothic"
# (malgun.ttf / malgunbd.ttf, normally in C:/Windows/Fonts).
#
# Run from the repo root:   bash tools/gen_fonts.sh
#
# If you add new on-screen Korean text, add the new characters to $HANGUL
# below (as a comma list of 0xXXXX code points) before regenerating, or the
# new glyphs will render blank.

set -euo pipefail
cd "$(dirname "$0")/.."

OUT_DIR="src/ui/fonts"
FONTS_DIR="${WINDIR:-/c/Windows}/Fonts"
ASCII="0x20-0x7E,0xB0"   # printable ASCII + degree sign (°)

# Every Hangul syllable that appears in src/ui (labels + status strings).
# Re-extract after adding Korean: python -c "..." or just add the new 0xXXXX.
HANGUL="0xAC00,0xAC04,0xAC15,0xAC80,0xACB0,0xACBD,0xACF5,0xAD50,0xAD6D,0xAD8C,0xAE09,0xAE30,0xAE40,0xAEBC,0xB04A,0xB098,0xB0B4,0xB108,0xB124,0xB204,0xB274,0xB2C8,0xB2E4,0xB2E8,0xB2F5,0xB300,0xB3D9,0xB428,0xB4DC,0xB530,0xB77C,0xB7C9,0xB85C,0xB8CC,0xB984,0xB9C8,0xB9D1,0xBA54,0xBAA8,0xBB34,0xBBF8,0xBC0F,0xBC14,0xBC30,0xBC84,0xBC88,0xBC94,0xBCC0,0xBCF5,0xBE60,0xC0AC,0xC0C1,0xC0C9,0xC120,0xC124,0xC18C,0xC1A1,0xC218,0xC2A4,0xC2B5,0xC2DC,0xC2E0,0xC2E4,0xC544,0xC57D,0xC5C6,0xC5D0,0xC5F0,0xC5F4,0xC608,0xC644,0xC678,0xC6A9,0xC6CC,0xC704,0xC73C,0xC744,0xC74C,0xC751,0xC758,0xC774,0xC778,0xC77C,0xC785,0xC788,0xC790,0xC791,0xC7A5,0xC7AC,0xC800,0xC801,0xC804,0xC815,0xC81C,0xC885,0xC8FC,0xC911,0xC9C0,0xC9C1,0xC9C4,0xC9C8,0xC9D0,0xCC28,0xCCAD,0xCCB4,0xCD08,0xCDE8,0xCF8C,0xD06C,0xD0DC,0xD0DD,0xD130,0xD1B5,0xD2B8,0xD2BC,0xD328,0xD32C,0xD3B8,0xD3F0,0xD48D,0xD544,0xD574,0xD604,0xD648,0xD654,0xD655,0xD658"

gen() {
  local outname=$1 size=$2 weight=$3 bpp=${4:-4} compress=${5:-1}
  local src="$FONTS_DIR/malgun.ttf"
  [ "$weight" = "bold" ] && src="$FONTS_DIR/malgunbd.ttf"
  local extra=()
  [ "$compress" = "0" ] && extra+=(--no-compress)
  echo "Generating $outname ($size px, $weight)..."
  npx --yes lv_font_conv \
    --font "$src" -r "$ASCII" -r "$HANGUL" \
    --size "$size" --bpp "$bpp" "${extra[@]}" --format lvgl \
    --lv-include lvgl.h \
    -o "$OUT_DIR/${outname}.c" \
    --lv-font-name "$outname"
}

mkdir -p "$OUT_DIR"
gen ui_font_xs  14 regular
gen ui_font_sm  18 regular
gen ui_font_md  22 bold
# xxl left uncompressed: it's the hero readout, worth the few extra KB of
# flash to rule out any compressed-glyph edge case at this size/weight.
gen ui_font_xxl 34 bold 4 0

echo "Done. Regenerated fonts in $OUT_DIR/"
