#!/usr/bin/env bash
# Regenerate the custom Korean+Latin subset fonts used by src/ui.
#
# Requires: node/npx (uses lv_font_conv via npx) and Windows "Malgun Gothic"
# (malgun.ttf / malgunbd.ttf, normally in C:/Windows/Fonts).
#
# Run from the repo root:   bash tools/gen_fonts.sh
#
# If you add new on-screen Korean text, add the new characters to $HANGUL
# below (as a comma list of 0xXXXX code points) before regenerating, or the
# new glyphs will render blank.

set -euo pipefail
cd "$(dirname "$0")/.."

OUT_DIR="src/ui/fonts"
FONTS_DIR="${WINDIR:-/c/Windows}/Fonts"
ASCII="0x20-0x7E,0xB0,0xB3,0xB5,0xB7,0x2082"   # printable ASCII + ° ³ µ · ₂ (µg/m³, CO₂)

# Every Hangul syllable that appears in src/ui (labels + status strings).
# Re-extract after adding Korean: python -c "..." or just add the new 0xXXXX.
HANGUL="0xAC00,0xAC04,0xAC12,0xAC15,0xAC19,0xAC1C,0xAC80,0xACA9,0xACB0,0xACBD,0xACC4,0xACE0,0xACF5,0xACFC,0xAD50,0xAD6D,0xAD8C,0xAE08,0xAE09,0xAE30,0xAE40,0xAEBC,0xB04A,0xB04C,0xB098,0xB0B4,0xB108,0xB124,0xB144,0xB204,0xB274,0xB294,0xB2C8,0xB2E4,0xB2E8,0xB2EB,0xB2F5,0xB2F9,0xB300,0xB354,0xB3C4,0xB3D9,0xB418,0xB428,0xB450,0xB4A4,0xB4DC,0xB4E4,0xB530,0xB54C,0xB77C,0xB7C9,0xB825,0xB85C,0xB8CC,0xB958,0xB974,0xB97C,0xB984,0xB9AC,0xB9B0,0xB9C8,0xB9CC,0xB9D1,0xB9E4,0xBA54,0xBA74,0xBA85,0xBAA8,0xBABB,0xBB34,0xBB38,0xBBF8,0xBC00,0xBC0F,0xBC14,0xBC18,0xBC29,0xBC30,0xBC31,0xBC84,0xBC88,0xBC94,0xBCC0,0xBCF4,0xBCF5,0xBCF8,0xBD80,0xBD84,0xBE0C,0xBE44,0xBE60,0xC068,0xC0AC,0xC0C1,0xC0C9,0xC11C,0xC120,0xC124,0xC138,0xC18C,0xC18D,0xC1A1,0xC218,0xC2A4,0xC2B5,0xC2DC,0xC2DD,0xC2E0,0xC2E4,0xC4F8,0xC544,0xC548,0xC555,0xC57D,0xC591,0xC5B4,0xC5B8,0xC5C6,0xC5D0,0xC5EC,0xC5F0,0xC5F4,0xC608,0xC624,0xC644,0xC678,0xC694,0xC6A9,0xC6B0,0xC6B4,0xC6CC,0xC6D0,0xC6D4,0xC704,0xC73C,0xC740,0xC744,0xC74C,0xC751,0xC758,0xC774,0xC778,0xC77C,0xC785,0xC788,0xC790,0xC791,0xC794,0xC7A0,0xC7A5,0xC7AC,0xC800,0xC801,0xC804,0xC811,0xC815,0xC81C,0xC870,0xC885,0xC88B,0xC8FC,0xC900,0xC911,0xC9C0,0xC9C1,0xC9C4,0xC9C8,0xC9D0,0xCC28,0xCC3D,0xCC3E,0xCCAD,0xCCB4,0xCD08,0xCD5C,0xCDE8,0xCE58,0xCE68,0xCE74,0xCE94,0xCEE4,0xCF54,0xCF8C,0xD06C,0xD070,0xD0C0,0xD0DC,0xD0DD,0xD130,0xD1A0,0xD1B5,0xD2B8,0xD2BC,0xD328,0xD32C,0xD398,0xD3B8,0xD3F0,0xD48D,0xD544,0xD558,0xD55C,0xD568,0xD574,0xD588,0xD589,0xD604,0xD615,0xD638,0xD648,0xD654,0xD655,0xD658,0xD68C,0xD6C4,0xD734,0xD788"

gen() {
  local outname=$1 size=$2 weight=$3 bpp=${4:-4} compress=${5:-1}
  local src="$FONTS_DIR/malgun.ttf"
  [ "$weight" = "bold" ] && src="$FONTS_DIR/malgunbd.ttf"
  local extra=()
  [ "$compress" = "0" ] && extra+=(--no-compress)
  echo "Generating $outname ($size px, $weight)..."
  npx --yes lv_font_conv \
    --font "$src" -r "$ASCII" -r "$HANGUL" \
    --size "$size" --bpp "$bpp" "${extra[@]}" --format lvgl \
    --lv-include lvgl.h \
    -o "$OUT_DIR/${outname}.c" \
    --lv-font-name "$outname"
}

mkdir -p "$OUT_DIR"
gen ui_font_xs  14 regular
gen ui_font_sm  18 regular
gen ui_font_md  22 bold
# xxl left uncompressed: it's the hero readout, worth the few extra KB of
# flash to rule out any compressed-glyph edge case at this size/weight.
gen ui_font_xxl 34 bold 4 0

# Digits only, for dashboard C's big temperature readout (keeps it small).
echo "Generating ui_font_hero (50 px, bold, digits)..."
npx --yes lv_font_conv   --font "$FONTS_DIR/malgunbd.ttf" -r "0x20,0x2D,0x2E,0x30-0x39"   --size 50 --bpp 4 --format lvgl --lv-include lvgl.h   -o "$OUT_DIR/ui_font_hero.c" --lv-font-name ui_font_hero

# Dashboard C: regular-weight "AQI 32" header and 12 px small text (scale, mode detail line).
echo "Generating ui_font_aqi (32 px, regular, AQI digits)..."
npx --yes lv_font_conv --font "$FONTS_DIR/malgun.ttf" -r "0x20,0x2D,0x30-0x39,0x41,0x49,0x51" --size 32 --bpp 4 --format lvgl --lv-include lvgl.h -o "$OUT_DIR/ui_font_aqi.c" --lv-font-name ui_font_aqi
echo "Generating ui_font_tiny (12 px, regular, Latin + Hangul)..."
npx --yes lv_font_conv --font "$FONTS_DIR/malgun.ttf" -r "$ASCII" -r "$HANGUL" --size 12 --bpp 4 --format lvgl --lv-include lvgl.h -o "$OUT_DIR/ui_font_tiny.c" --lv-font-name ui_font_tiny

echo "Done. Regenerated fonts in $OUT_DIR/"
